"""Build a reproducible local source release without publishing it."""

from __future__ import annotations

import hashlib
import json
import stat
import tomllib
import zipfile
from datetime import datetime
from pathlib import Path

from tools.release_safety import assert_release_safe, assert_zip_safe, git_identity

PROJECT_ROOT = Path(__file__).resolve().parents[2]
PACKAGE_VERSION = tomllib.loads(
    (PROJECT_ROOT / "source" / "pyproject.toml").read_text(encoding="utf-8")
)["project"]["version"]
RELEASE_DIR = PROJECT_ROOT / "release"
ARCHIVE_NAME = "KOMI_Report_V5_1_0_Source.zip"
INCLUDE_ROOTS = (
    PROJECT_ROOT / "Open KOMI Report Web.command",
    PROJECT_ROOT / "docs" / "PILOT_RELEASE_CHECKLIST.md",
    PROJECT_ROOT / "docs" / "REGISTRATION_DATA_NOTICE.md",
    PROJECT_ROOT / "docs" / "RELEASE_RUNBOOK.md",
    PROJECT_ROOT / "docs" / "RELEASE_SUPPORT_AND_RECOVERY.md",
    PROJECT_ROOT / "docs" / "SUPPORT_MATRIX.md",
    PROJECT_ROOT / "docs" / "data-storage-overview.html",
    PROJECT_ROOT / "docs" / "data-storage-overview.png",
    PROJECT_ROOT / "docs" / "sync-rule-flowchart.html",
    PROJECT_ROOT / "docs" / "sync-rule-flowchart.png",
    PROJECT_ROOT / "source",
    PROJECT_ROOT / "web",
)
EXCLUDED_PARTS = {
    ".git",
    ".next",
    ".pytest_cache",
    ".ruff_cache",
    ".venv",
    "__pycache__",
    "build",
    "dist",
    "logs",
    "node_modules",
    "runtime-cache",
}
EXCLUDED_SUFFIXES = {
    ".db",
    ".db-shm",
    ".db-wal",
    ".csv",
    ".env",
    ".key",
    ".log",
    ".p12",
    ".pem",
    ".pyc",
    ".sqlite",
    ".sqlite3",
    ".tsbuildinfo",
    ".xls",
    ".xlsx",
}
EXCLUDED_NAMES = {
    ".DS_Store",
    ".env",
    ".env.local",
    "next-env.d.ts",  # generated by Next.js during install/build
    "overview-v2-preview.png",  # local UI evidence, not a runtime asset
    "status.css",  # retired; globals.css owns the live styles
}
ZIP_TIMESTAMP = (2026, 1, 1, 0, 0, 0)


def _included_files() -> list[Path]:
    files: list[Path] = []
    for root in INCLUDE_ROOTS:
        candidates = (root,) if root.is_file() else root.rglob("*")
        for path in candidates:
            if not path.is_file():
                continue
            relative = path.relative_to(PROJECT_ROOT)
            if any(part in EXCLUDED_PARTS for part in relative.parts):
                continue
            if path.name in EXCLUDED_NAMES or path.name.startswith(".env."):
                continue
            if any(path.name.endswith(suffix) for suffix in EXCLUDED_SUFFIXES):
                continue
            files.append(path)
    return sorted(set(files), key=lambda item: item.relative_to(PROJECT_ROOT).as_posix())


def build_source_archive() -> tuple[Path, str, int]:
    RELEASE_DIR.mkdir(parents=True, exist_ok=True)
    archive = RELEASE_DIR / ARCHIVE_NAME
    files = _included_files()
    assert_release_safe(files, root=PROJECT_ROOT)
    commit, source_state = git_identity(PROJECT_ROOT)
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as output:
        for path in files:
            relative = path.relative_to(PROJECT_ROOT).as_posix()
            info = zipfile.ZipInfo(relative, ZIP_TIMESTAMP)
            mode = path.stat().st_mode
            info.external_attr = (stat.S_IMODE(mode) & 0xFFFF) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            output.writestr(info, path.read_bytes(), compresslevel=9)
        identity_info = zipfile.ZipInfo("SOURCE_COMMIT.txt", ZIP_TIMESTAMP)
        identity_info.external_attr = 0o644 << 16
        identity_info.compress_type = zipfile.ZIP_DEFLATED
        output.writestr(identity_info, f"{commit}\n".encode("ascii"), compresslevel=9)
    assert_zip_safe(archive)
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    checksum = archive.with_suffix(archive.suffix + ".sha256")
    checksum.write_text(f"{digest}  {archive.name}\n", encoding="utf-8")
    artifact_identity = f"komi-report-v5-source-{PACKAGE_VERSION}-{commit[:12]}"
    manifest = {
        "version": PACKAGE_VERSION,
        "package_version": PACKAGE_VERSION,
        "artifact": archive.name,
        "artifact_identity": artifact_identity,
        "git_commit": commit,
        "source_state": source_state,
        "sha256": digest,
        "file_count": len(files) + 1,
        "build_time": datetime.now().astimezone().isoformat(timespec="seconds"),
        "publish_state": "local-only",
    }
    (RELEASE_DIR / "MANIFEST.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return archive, digest, len(files) + 1


if __name__ == "__main__":
    result, sha256, count = build_source_archive()
    print(f"{result}\nfiles={count}\nsha256={sha256}")
