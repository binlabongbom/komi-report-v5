#!/usr/bin/env python3
"""Validate that a launcher is using the canonical synced source tree."""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import sys
import tomllib
from pathlib import Path

MINIMUM_PYTHON = (3, 11)
DESKTOP_FILES = (
    "app.py",
    "config.py",
    "database.py",
    "i18n.py",
    "migrations.py",
    "observability.py",
    "pages.py",
    "parser.py",
    "parser_profiles.py",
    "runtime_config.py",
    "ui_consistency.py",
    "v5_pages.py",
    "web_api.py",
    "widgets.py",
    "pyproject.toml",
    "requirements.lock.txt",
    "uv.lock",
)
WEB_FILES = DESKTOP_FILES
DESKTOP_DIRS = ("services", "ui", "komi_snmp_profiler", "tools")
DESKTOP_SUFFIXES = {".py", ".json"}
WEB_EXCLUDED_DIRS = {".next", "node_modules", "__pycache__"}
WEB_EXCLUDED_PATHS = {
    "app/status.css",  # retired; globals.css owns these styles
    "next-env.d.ts",  # generated by Next.js during install/build
}


def _source_fingerprint(source_dir: Path, names: tuple[str, ...]) -> str:
    digest = hashlib.sha256()
    for name in names:
        path = source_dir / name
        if not path.is_file():
            raise FileNotFoundError(f"ไม่พบไฟล์ source ที่จำเป็น: {path}")
        digest.update(name.encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    for directory_name in DESKTOP_DIRS:
        directory = source_dir / directory_name
        if not directory.is_dir():
            raise FileNotFoundError(f"ไม่พบโฟลเดอร์ source ที่จำเป็น: {directory}")
        for path in sorted(directory.rglob("*"), key=lambda item: item.as_posix()):
            if not path.is_file() or path.suffix not in DESKTOP_SUFFIXES:
                continue
            if "__pycache__" in path.parts:
                continue
            relative = path.relative_to(source_dir).as_posix()
            digest.update(relative.encode("utf-8"))
            digest.update(b"\0")
            digest.update(path.read_bytes())
            digest.update(b"\0")
    return digest.hexdigest()


def _web_fingerprint(source_dir: Path, web_dir: Path) -> str:
    digest = hashlib.sha256()
    digest.update(_source_fingerprint(source_dir, WEB_FILES).encode("ascii"))
    digest.update(b"\0")
    if not web_dir.is_dir():
        raise FileNotFoundError(f"ไม่พบ Web source กลาง: {web_dir}")
    for path in sorted(web_dir.rglob("*"), key=lambda item: item.as_posix()):
        if not path.is_file():
            continue
        relative = path.relative_to(web_dir)
        if any(part in WEB_EXCLUDED_DIRS for part in relative.parts):
            continue
        if relative.as_posix() in WEB_EXCLUDED_PATHS:
            continue
        if path.name.startswith(".env") and path.name.endswith(".local"):
            continue
        if path.name.endswith(".tsbuildinfo"):
            continue
        digest.update(f"web/{relative.as_posix()}".encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("desktop", "web", "doctor"), nargs="?", default="doctor")
    parser.add_argument("--json", action="store_true", dest="as_json")
    args = parser.parse_args()

    if sys.version_info < MINIMUM_PYTHON:
        print("KOMI Report V5 ต้องใช้ Python 3.11 ขึ้นไป", file=sys.stderr)
        return 2

    source_dir = Path(__file__).resolve().parents[1]
    project_root = source_dir.parent
    web_dir = project_root / "web"
    pyproject = source_dir / "pyproject.toml"
    if not pyproject.is_file():
        print(f"ไม่พบ pyproject.toml ใน source กลาง: {source_dir}", file=sys.stderr)
        return 3

    try:
        metadata = tomllib.loads(pyproject.read_text(encoding="utf-8"))["project"]
        source_id = (
            _web_fingerprint(source_dir, web_dir)
            if args.mode == "web"
            else _source_fingerprint(source_dir, DESKTOP_FILES)
        )
    except (OSError, KeyError, tomllib.TOMLDecodeError) as exc:
        print(f"อ่าน source กลางไม่สำเร็จ: {exc}", file=sys.stderr)
        print("ตรวจว่า canonical source ใน Projects/dev อยู่ครบและอ่านได้", file=sys.stderr)
        return 4

    conflict_locations = (
        project_root,
        source_dir,
        source_dir / "services",
        source_dir / "tests",
        source_dir / "tools",
        project_root / "web",
        project_root / "web" / "app",
        project_root / "web" / "app" / "login",
    )
    conflicts = sorted(
        path
        for location in conflict_locations
        if location.is_dir()
        for path in location.glob("*-Wongsakorn’s MacBook Pro.*")
    )
    result = {
        "app": metadata.get("name", "komi-report-v5"),
        "version": metadata.get("version", "unknown"),
        "mode": args.mode,
        "python": platform.python_version(),
        "platform": platform.system(),
        "project_root": str(project_root),
        "source_root": str(source_dir),
        "source_id": source_id,
        "conflict_copy_count": len(conflicts),
    }
    if args.as_json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        print(f"KOMI Report V5 {result['version']} | {result['platform']} | Python {result['python']}")
        print(f"Shared source: {result['source_root']}")
        print(f"Source ID: {result['source_id']}")
        if conflicts:
            print(f"คำเตือน: พบ OneDrive conflict copy {len(conflicts)} ไฟล์")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
